import { useState } from "react";

// User guide embedded on the Ahrefs filter page.
export function AhrefsGuide() {
  const [open, setOpen] = useState(false);
  return (
    <div className="guide">
      <button className="guide-toggle" onClick={() => setOpen(!open)}>
        📖 Руководство пользователя: Фильтр качества доменов {open ? "▲" : "▼"}
      </button>
      {open && (
        <div className="guide-body">
          <p>
            Инструмент — количественный фильтр для массового анализа доменов на
            основе выгрузок из Ahrefs Batch Analysis. Он автоматически отсеивает
            откровенный «мусор», оценивает качество оставшихся доменов по
            стобалльной шкале и распределяет их по категориям. Работает по
            принципу ранжирования: не просто делит на «хорошие» и «плохие», а
            выстраивает по уровню качества, оставляя финальное решение за вами.
          </p>

          <h4>📌 Что делает инструмент, а что — нет</h4>
          <p><b>Делает автоматически:</b></p>
          <ul>
            <li>Очищает и нормализует загруженные данные.</li>
            <li>Беспощадно удаляет «мертвые» сайты и очевидный спам.</li>
            <li>Рассчитывает единый балл качества (0–100) для каждого домена.</li>
            <li>Сортирует сайты по группам (тирам) на основе балла.</li>
            <li>Расставляет флаги (следы взлома, нецелевое ГЕО, азиатский трафик).</li>
          </ul>
          <p><b>НЕ делает</b> (это происходит на других этапах):</p>
          <ul>
            <li>Не скачивает данные из Ahrefs — файл вы загружаете сами.</li>
            <li>Не определяет тематику сайта (казино/фарма и т.п.).</li>
            <li>Не анализирует историю домена (Wayback, индексация в Google).</li>
            <li>Не делает запросов к сторонним сервисам.</li>
          </ul>

          <h4>⚙️ Как происходит фильтрация</h4>
          <p>
            <b>Шаг 1. Загрузка.</b> Загрузите файл экспорта Ahrefs. Обязательны
            колонки: <code>Target</code>, <code>Domain Rating</code>,
            <code> Ref. domains / All</code>, <code>Ref. domains / Followed</code>,
            <code> Backlinks / All</code>. Пустые значения трактуются как нули.
          </p>
          <p>
            <b>Шаг 2. Жёсткий отсев</b> (~6%). Домен попадает в корзину, если:
            мёртвый (нет ни DR, ни полезных ссылок); массовый спам (много ссылок,
            но все nofollow); слабый (почти нет ссылающихся доменов и нулевой
            рейтинг); ферма/взлом (аномально много исходящих при нулевой органике).
          </p>
          <p>
            <b>Шаг 3. Умная оценка (0–100).</b> Учитываются: авторитет (DR),
            качественные (followed) ссылки, разнообразие сетей (анти-PBN),
            органический трафик (бонус) и штрафы за подозрительный профиль.
          </p>
          <p>
            <b>Шаг 4. Распределение по тирам.</b> По умолчанию: <b>A</b> — балл
            ≥55 (лучшие); <b>B</b> — 40–54 (крепкие); <b>C</b> — 28–39 (слабые, но
            живые); <b>Review</b> — &lt;28 (ручной просмотр); <b>Rejected</b> —
            мусор из шага 2.
          </p>

          <h4>🚩 Флаги</h4>
          <ul>
            <li><b>Спам-пол</b> (flag_spam_floor): ссылки формально есть, но без ценности.</li>
            <li><b>Ферма</b> (flag_burn): много исходящих ссылок, возможен взлом.</li>
            <li><b>Нецелевое ГЕО</b> (flag_geo_review): трафик из ненужных стран.</li>
            <li>
              🔴 <b>Азиатский трафик</b> (flag_cjk): при основном трафике из стран
              с иероглифической письменностью домен принудительно уходит в
              <b> Review</b> — даже с идеальным баллом он не попадёт в A/B.
            </li>
          </ul>

          <h4>🎛 Настройки</h4>
          <p>
            В настройках можно менять строгость отсева, сдвигать границы тиров,
            менять веса метрик, задавать список целевых стран. <b>Любое изменение
            пересчитывает таблицу мгновенно</b> — файл заново грузить не нужно, вы
            сразу видите новую сводку по группам.
          </p>

          <h4>📊 Результаты</h4>
          <p>
            Готовая таблица с экспортом в CSV/TXT. Домены отсортированы от лучших к
            худшим, отклонённые — внизу. Видны категория, балл, флаги и причины
            отбраковки/отправки на ручную проверку.
          </p>
        </div>
      )}
    </div>
  );
}
